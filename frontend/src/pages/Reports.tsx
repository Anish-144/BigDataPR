import { Link } from "react-router-dom";
import { useTestRuns } from "../api/hooks";
import type { TestRunListItem } from "../api/types";
import { Card, Note, PageHeader } from "../components/ui/Card";
import { DataTable, type Column } from "../components/ui/DataTable";
import { ErrorPanel, EmptyState, SkeletonRows } from "../components/ui/states";
import { StatusBadge, Tag } from "../components/ui/Badge";
import { Icon } from "../components/ui/Icon";
import { fmtCompact, fmtDateTime, fmtInt } from "../lib/format";

const reportUrl = (id: string, format: "csv" | "md" | "json" | "html") => `/api/v1/reports/${encodeURIComponent(id)}?format=${format}`;

export default function Reports() {
  const q = useTestRuns(200);
  const cols: Column<TestRunListItem>[] = [
    {
      key: "name",
      header: "Test run",
      render: (t) => (
        <span className="flex flex-col">
          <span className="font-medium text-ink">{t.test_run_name ?? "—"}</span>
          <span className="mono text-2xs text-muted">{t.test_run_id}</span>
        </span>
      ),
    },
    { key: "status", header: "Status", render: (t) => <StatusBadge status={t.api_status ?? t.status} /> },
    { key: "started_at", header: "Started", render: (t) => <span className="whitespace-nowrap text-ink-2">{fmtDateTime(t.started_at)}</span> },
    { key: "time_mode", header: "Time mode", render: (t) => (t.time_mode ? <Tag>{t.time_mode}</Tag> : "—") },
    { key: "total_runs", header: "Runs", align: "right", render: (t) => fmtInt(t.total_runs ?? t.progress_tasks) },
    { key: "total_events", header: "Events", align: "right", render: (t) => fmtCompact(t.total_events) },
    { key: "triggered_by", header: "Triggered by", render: (t) => <span className="text-ink-2">{t.triggered_by ?? t.source}</span> },
    {
      key: "downloads",
      header: "Report",
      render: (t) => (
        <span className="flex flex-wrap items-center gap-1.5">
          <a className="btn btn-sm" href={reportUrl(t.test_run_id, "csv")} download={`agentshield_report_${t.test_run_id}.csv`}>
            <Icon name="download" size={13} /> CSV
          </a>
          <a className="btn btn-sm" href={reportUrl(t.test_run_id, "md")} download={`agentshield_report_${t.test_run_id}.md`}>
            <Icon name="download" size={13} /> Markdown
          </a>
          <a className="btn btn-sm" href={reportUrl(t.test_run_id, "json")} download={`agentshield_report_${t.test_run_id}.json`}>
            <Icon name="download" size={13} /> JSON
          </a>
          <a className="btn btn-sm" href={reportUrl(t.test_run_id, "html")} target="_blank" rel="noopener noreferrer">
            <Icon name="external" size={13} /> Open printable report (Save as PDF)
          </a>
        </span>
      ),
    },
    {
      key: "explore",
      header: "",
      render: (t) => (
        <Link className="link whitespace-nowrap text-xs" to={`/runs?test_run_id=${encodeURIComponent(t.test_run_id)}`}>
          Runs →
        </Link>
      ),
    },
  ];
  return (
    <div className="flex flex-col gap-4">
      <PageHeader
        title="Reports"
        description="Export a benchmark / regression report for any test run. Reports are generated by the API from lakehouse data at download time."
      />
      <Note>
        For a PDF, open the printable report and use your browser's Print → Save as PDF. Reports include estimated costs (local pricing table) and simulated latency/tokens
        from mock agents; anomaly and security counts are signals for review.
      </Note>
      <Card title="Test runs" subtitle={q.data ? `${q.data.test_runs.length} test runs` : undefined} bodyClassName="p-3">
        {q.isLoading ? (
          <SkeletonRows rows={8} />
        ) : q.isError && !q.data ? (
          <ErrorPanel error={q.error} onRetry={() => q.refetch()} />
        ) : q.data ? (
          <DataTable
            columns={cols}
            rows={q.data.test_runs}
            rowKey={(t) => t.test_run_id}
            dense
            maxHeight={720}
            caption="Test runs with report downloads"
            empty={<EmptyState title="No test runs yet">Start one from the Testing Lab.</EmptyState>}
          />
        ) : null}
      </Card>
    </div>
  );
}
