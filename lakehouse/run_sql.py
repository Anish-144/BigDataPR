"""Execute annotated SQL files against Trino.

Examples:
    python -m lakehouse.run_sql sql/01_schema_and_tables.sql
    python -m lakehouse.run_sql sql/02_performance_analytics.sql
    python -m lakehouse.run_sql sql/02_performance_analytics.sql --only p95_latency_by_version --param days=30
    python -m lakehouse.run_sql sql/0[2-8]*.sql --export docs/sql_outputs   # markdown + JSON results

Exit code is non-zero if any statement fails.
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
import time
from pathlib import Path
from typing import Any

from lakehouse.sql_catalog import coerce, load_file
from lakehouse.trino_client import QueryResult, run_query, wait_for_trino


def to_markdown(res: QueryResult, limit: int = 25) -> str:
    if not res.columns:
        return "_(no result set)_\n"
    def cell(v: Any) -> str:
        if isinstance(v, float):
            v = round(v, 4)
        s = json.dumps(v) if isinstance(v, (list, dict)) else ("NULL" if v is None else str(v))
        return s.replace("|", "\\|").replace("\n", " ")[:120]
    lines = ["| " + " | ".join(res.columns) + " |", "|" + "---|" * len(res.columns)]
    for r in res.rows[:limit]:
        lines.append("| " + " | ".join(cell(v) for v in r) + " |")
    if len(res.rows) > limit:
        lines.append(f"\n_{len(res.rows) - limit} more rows not shown_")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+")
    ap.add_argument("--only", action="append", help="run only these @query names")
    ap.add_argument("--param", action="append", default=[], help="key=value parameter override")
    ap.add_argument("--export", help="directory for markdown/JSON result exports")
    ap.add_argument("--wait", type=float, default=0, help="wait up to N seconds for Trino first")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--max-rows", type=int, default=1000)
    ap.add_argument("--retries", type=int, default=0, help="retry a failed statement N times (startup races)")
    args = ap.parse_args(argv)

    overrides = {}
    for p in args.param:
        k, _, v = p.partition("=")
        overrides[k] = coerce(v)
    if args.wait:
        wait_for_trino(args.wait)

    files: list[str] = []
    for pattern in args.files:
        files.extend(sorted(glob.glob(pattern)) or [pattern])
    export_dir = Path(args.export) if args.export else None
    if export_dir:
        export_dir.mkdir(parents=True, exist_ok=True)

    failures = 0
    for f in files:
        for st in load_file(f):
            if args.only and st.name not in args.only:
                continue
            label = st.name or f"{Path(f).name}#{st.index}"
            params_for = {k: v for k, v in overrides.items() if k in st.defaults}
            res, error = None, None
            for attempt in range(args.retries + 1):
                try:
                    sql, params = st.bind(params_for)
                    res = run_query(sql, params or None, max_rows=args.max_rows)
                    break
                except Exception as exc:
                    error = exc
                    if attempt < args.retries:
                        time.sleep(3 * (attempt + 1))
            if res is None:
                failures += 1
                print(f"[FAIL] {label}: {error}", file=sys.stderr)
                continue
            processed = res.stats.get("processedRows")
            print(f"[ OK ] {label}  rows={len(res.rows)}  elapsed={res.elapsed_ms:.0f} ms"
                  + (f"  processedRows={processed}" if processed is not None else ""))
            if st.name and not args.quiet:
                print(to_markdown(res, limit=10))
            if export_dir and st.name:
                (export_dir / f"{st.name}.md").write_text(
                    f"<!-- generated by lakehouse.run_sql from {Path(f).name} -->\n"
                    f"**Executed:** elapsed {res.elapsed_ms:.0f} ms, rows {len(res.rows)}, "
                    f"processedRows {processed}, processedBytes {res.stats.get('processedBytes')}\n\n"
                    + to_markdown(res), encoding="utf-8")
                (export_dir / f"{st.name}.json").write_text(json.dumps(
                    {"query": st.name, "file": Path(f).name, "tags": st.tags, "elapsed_ms": res.elapsed_ms,
                     "stats": res.stats, "columns": res.columns, "rows": res.rows[:200]}, indent=2, default=str),
                    encoding="utf-8")
    print(f"done: {failures} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
